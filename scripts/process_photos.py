"""Turn high-res originals into web-sized WebP files + a manifest.

Layout:
  photos/originals/<collection>/*.jpg   (gitignored; your full-res files)
  photos/originals/<collection>/meta.json (optional: {"title": "...", "subtitle": "...",
                                           "order": ["R0001.jpg", ...]})

Photos are shown in filename order, except that any listed in "order" come
first, in that order.

Output:
  photos/<collection>/<name>-{640,1280,2400}.webp
  photos/collections.js  (manifest loaded by photos.html)

Collections are listed in reverse folder-name order, so prefix folders with a
date (e.g. 2025-10-tokyo) to put the newest first.

Run: uv run scripts/process_photos.py
"""

import json
import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent / "photos"
ORIGINALS = ROOT / "originals"
WIDTHS = [640, 1280, 2400]
QUALITY = 80
EXTENSIONS = {".jpg", ".jpeg", ".png", ".tif", ".tiff", ".webp"}


def process_photo(src: Path, out_dir: Path) -> dict:
    with Image.open(src) as im:
        im = ImageOps.exif_transpose(im).convert("RGB")
        w, h = im.size
        for target in WIDTHS:
            dest = out_dir / f"{src.stem}-{target}.webp"
            if dest.exists() and dest.stat().st_mtime > src.stat().st_mtime:
                continue
            scale = min(1, target / w)
            resized = im.resize((round(w * scale), round(h * scale)), Image.LANCZOS)
            # Saving without exif= drops all metadata, including GPS
            resized.save(dest, "WEBP", quality=QUALITY, method=6)
        r, g, b = im.resize((1, 1), Image.BOX).getpixel((0, 0))
    return {"name": src.stem, "w": w, "h": h, "color": f"#{r:02x}{g:02x}{b:02x}"}


def main() -> None:
    ORIGINALS.mkdir(parents=True, exist_ok=True)
    collections = []
    for folder in sorted((p for p in ORIGINALS.iterdir() if p.is_dir()), reverse=True):
        meta_path = folder / "meta.json"
        meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
        out_dir = ROOT / folder.name
        out_dir.mkdir(exist_ok=True)

        order = meta.get("order", [])
        sources = sorted(
            (p for p in folder.iterdir() if p.suffix.lower() in EXTENSIONS),
            key=lambda p: (order.index(p.name) if p.name in order else len(order), p.name),
        )

        photos = []
        for src in sources:
            print(f"{folder.name}/{src.name}")
            photos.append(process_photo(src, out_dir))

        collections.append({
            "slug": folder.name,
            "title": meta.get("title", re.sub(r"^[\d-]+", "", folder.name).replace("-", " ").title()),
            "subtitle": meta.get("subtitle", ""),
            "photos": photos,
        })

    manifest = json.dumps(collections, indent=2)
    (ROOT / "collections.js").write_text(
        "// Generated by scripts/process_photos.py — do not edit\n"
        f"const PHOTO_COLLECTIONS = {manifest}\n"
    )
    print(f"Wrote {sum(len(c['photos']) for c in collections)} photos in {len(collections)} collections")


if __name__ == "__main__":
    main()
